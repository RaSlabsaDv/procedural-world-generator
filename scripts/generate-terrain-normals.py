"""Original periodic terrain normal layers, CC0; standard-library offline preparation."""
from pathlib import Path
import hashlib
import math
import random
import struct
import zlib

SIZE = 128
NAMES = ('grass', 'soil', 'sand', 'rock', 'snow')
STRENGTHS = (1.2, 1.0, .7, 2.2, .45)
FREQUENCIES = (3, 7, 13, 23)
WEIGHTS = (.08, .18, .34, .40)
OUTPUT = Path(__file__).resolve().parents[1] / 'src/client/public/textures/microdetail'


def sampler(seed, strength):
    rng = random.Random(seed)
    layers = [(n, [[rng.random() for _ in range(n)] for _ in range(n)]) for n in FREQUENCIES]

    def normal(u, v):
        dx = dy = 0.0
        for (n, lattice), weight in zip(layers, WEIGHTS):
            x, y = u*n, v*n
            ix, iy = math.floor(x), math.floor(y)
            tx, ty = x-ix, y-iy
            sx, sy = tx**3*(tx*(tx*6-15)+10), ty**3*(ty*(ty*6-15)+10)
            dsx, dsy = 30*tx*tx*(tx-1)**2, 30*ty*ty*(ty-1)**2
            a, b = lattice[iy % n][ix % n], lattice[iy % n][(ix+1) % n]
            c, d = lattice[(iy+1) % n][ix % n], lattice[(iy+1) % n][(ix+1) % n]
            # Height amplitude is weight/n: spatial derivative cancels the n.
            dx += weight*dsx*((b-a)*(1-sy)+(d-c)*sy)
            dy += weight*dsy*((c-a)*(1-sx)+(d-b)*sx)
        nx, ny = -strength*dx, -strength*dy
        length = math.sqrt(nx*nx+ny*ny+1)
        return tuple(round(128+127*v/length) for v in (nx, ny, 1))
    return normal


def generate():
    raw = bytearray()
    for i, strength in enumerate(STRENGTHS):
        sample = sampler(1801+i, strength)
        for y in range(SIZE):
            raw.append(0)
            for x in range(SIZE):
                raw.extend(sample(x/SIZE, y/SIZE))
    def chunk(kind, data):
        return struct.pack('>I', len(data))+kind+data+struct.pack('>I', zlib.crc32(kind+data)&0xffffffff)
    return (b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR', struct.pack('>IIBBBBB', SIZE, SIZE*5, 8, 2, 0, 0, 0))
            +chunk(b'IDAT', zlib.compress(bytes(raw), 9))+chunk(b'IEND', b''))


if __name__ == '__main__':
    OUTPUT.mkdir(parents=True, exist_ok=True)
    data = generate()
    (OUTPUT/'normals.png').write_bytes(data)
    (OUTPUT/'ASSETS.md').write_text(
        '# Terrain microdetail normals\n\n'
        'Original CC0-1.0 procedural RGB8 normal atlas, generated by\n'
        'scripts/generate-terrain-normals.py using periodic quintic value fields\n'
        'and analytical derivatives. No external source images or baked lighting.\n\n'
        '128x640 pixels: five vertical 128-square layers Grass/Soil/Sand/Rock/Snow.\n'
        'Seeds 1801..1805; frequencies 3/7/13/23; weights .08/.18/.34/.40 divided\n'
        'by frequency for scalar heights. Derivative strengths 1.2/1/.7/2.2/.45.\n'
        'Encode round(128+127*N); neutral RGB128/128/255 is exact.\n'
        'Load as linear RGBA data into five separate array layers; repeat and mip\n'
        'filter per layer to prevent atlas bleed. No bitmap editing dependency.\n\n'
        f'SHA256: {hashlib.sha256(data).hexdigest()}\nEncoded bytes: {len(data)}\n')
